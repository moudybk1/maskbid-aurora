// Generates packages/contracts/src/generated.ts from Foundry artifacts and deployments/*.json.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts/out");
const abi = (name) => JSON.parse(readFileSync(join(out, `${name}.sol/${name}.json`), "utf8")).abi;

const deployments = {};
const depDir = join(root, "contracts/deployments");
mkdirSync(depDir, { recursive: true });
for (const f of readdirSync(depDir).filter((f) => f.endsWith(".json"))) {
  const d = JSON.parse(readFileSync(join(depDir, f), "utf8"));
  deployments[String(d.chainId)] = d;
}

const file = `// Generated by scripts/sync-abi.mjs. Do not edit.
export const auctionAbi = ${JSON.stringify(abi("MaskBidAuction"))} as const;
export const assetAbi = ${JSON.stringify(abi("MaskBidAsset"))} as const;
export const registryAbi = ${JSON.stringify(abi("ParticipantRegistry"))} as const;
export const tokenAbi = ${JSON.stringify(abi("MockUSDC"))} as const;
export interface Deployment {
  chainId: number; auction: \`0x\${string}\`; asset: \`0x\${string}\`; registry: \`0x\${string}\`; token: \`0x\${string}\`;
  callbackSender: \`0x\${string}\`; nearAdapterAccount: string; solverCodeHash: \`0x\${string}\`; configHash: \`0x\${string}\`;
  profile: string; deployBlock: number; deployer: \`0x\${string}\`; xccPrecompile?: \`0x\${string}\`;
}
export const deployments: Record<string, Deployment> = ${JSON.stringify(deployments, null, 2)};
`;
mkdirSync(join(root, "packages/contracts/src"), { recursive: true });
writeFileSync(join(root, "packages/contracts/src/generated.ts"), file);
console.log("generated.ts written; deployments:", Object.keys(deployments).join(", ") || "none");
